FONT = "Microsoft YaHei"


def set_run(run, size=11, bold=False, color=(0x1A, 0x1F, 0x2E)):
    run.font.name = FONT
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = RGBColor(*color)


def add_para(doc, text, size=11, bold=False, color=(0x1A, 0x1F, 0x2E), space_after=4, space_before=0, indent=True):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.line_spacing = 1.28
    if indent:
        p.paragraph_format.first_line_indent = Cm(0.74)
    run = p.add_run(text)
    set_run(run, size=size, bold=bold, color=color)
    return p


def add_h(doc, text, size=13, color=(0x1F, 0x3A, 0x8A), space_before=12):
    return add_para(doc, text, size=size, bold=True, color=color, space_before=space_before, space_after=3, indent=False)


def add_cue(doc, text):
    return add_para(doc, text, size=9.5, color=(0x6B, 0x7A, 0x90), space_after=5, indent=False)


